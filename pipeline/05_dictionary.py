"""Stage 5, data dictionary: check and publish the meaning of every column.

The definitions are written by hand, one row per table and column, in
dictionary/definitions.csv (table, column, type, meaning, rule). A row with an empty
column describes the table itself. This script turns them into
dictionary/data_dictionary.md (to read) and dictionary/data_dictionary.csv (to filter
or open in Excel).

With --dbs and --study it first checks the definitions against the databases that
stages 1-4 built, and stops with a list of problems when:
  - a column in a database has no definition, or its type differs from the definition;
  - a study table (stages 3-4) has a definition for a column it does not have.
Raw columns may be defined but absent, because FDA added fields over the years
(for example prod_ai in 2014Q3), so a database of early quarters lacks them.
With --stats the published dictionary also shows how many rows fill each column.

Usage:
    python 05_dictionary.py                                   (publish from definitions)
    python 05_dictionary.py --dbs historical.duckdb current.duckdb --study study.duckdb
"""

import argparse
import sys
from pathlib import Path

from common import ROOT, connect, read_csv, write_csv

DEFINITIONS = ROOT / "dictionary" / "definitions.csv"
STUDY_TABLES = (
    "drug_classes",
    "cases",
    "rq1_cases",
    "rq1_counts",
    "rq1_terms",
    "rq2_cases",
    "rq2_monthly",
    "rq3_cases",
)


def actual_columns(con, schema):
    """{(table, column): type} for every table in ``schema`` of the open database."""
    cols = con.execute(
        """SELECT table_name, column_name, data_type FROM duckdb_columns()
        WHERE schema_name = ? AND database_name = current_database()""",
        [schema],
    ).fetchall()
    prefix = "raw." if schema == "raw" else ""
    return {(prefix + t, c): ty for t, c, ty in cols}


def fill_counts(con, table, columns):
    name = table.split(".")[-1] if table.startswith("raw.") else table
    full = f"raw.{name}" if table.startswith("raw.") else name
    parts = ", ".join(f'count("{c}")' for c in columns)
    total, *counts = con.execute(f"SELECT count(*), {parts} FROM {full}").fetchone()
    return total, dict(zip(columns, counts))


def check(definitions, dbs, study, stats):
    """Compare definitions with the built databases; returns (problems, fill %)."""
    defined = {(d["table"], d["column"]): d["type"] for d in definitions if d["column"]}
    found, fill = {}, {}
    for path, schema in [*((db, "raw") for db in dbs), (study, "main")]:
        con = connect(path, read_only=True)
        columns = actual_columns(con, schema)
        found.update(columns)
        if stats:
            for table in sorted({t for t, _ in columns}):
                names = [c for t, c in columns if t == table]
                total, counts = fill_counts(con, table, names)
                for c in names:
                    old = fill.get((table, c), (0, 0))
                    fill[(table, c)] = (old[0] + total, old[1] + counts[c])
        con.close()
    problems = []
    for key, typ in sorted(found.items()):
        if key[0] not in STUDY_TABLES and not key[0].startswith("raw."):
            continue  # scratch tables are not part of the study
        if key not in defined:
            problems.append(f"no definition for {key[0]}.{key[1]} ({typ})")
        elif defined[key] != typ:
            problems.append(f"{key[0]}.{key[1]}: defined as {defined[key]}, database has {typ}")
    for table, column in sorted(defined):
        if table in STUDY_TABLES and (table, column) not in found:
            problems.append(f"{table}.{column} is defined but the table has no such column")
    pct = {k: f"{100 * n / total:.1f}" if total else "" for k, (total, n) in fill.items()}
    return problems, pct


def publish(definitions, out, pct):
    rows, lines = (
        [],
        [
            "# Data dictionary",
            "",
            "Generated by `pipeline/05_dictionary.py` from",
            "[definitions.csv](definitions.csv); edit that file, not this one.",
            "Each column links to the rule that defines it. Raw tables hold FDA's values",
            "unchanged (all text); FDA's own field descriptions are in the `ASC_NTS` file of",
            "each quarterly ZIP.",
            "",
        ],
    )
    tables = [d for d in definitions if not d["column"]]
    lines += ["| Table | What it holds |", "|---|---|"]
    lines += [f"| [`{t['table']}`](#{anchor(t['table'])}) | {t['meaning']} |" for t in tables]
    for t in tables:
        rule = f" [Rule]({t['rule']})" if t["rule"] else ""
        lines += ["", f"## `{t['table']}`", "", t["meaning"] + rule, ""]
        header = "| Column | Type | Meaning | Rule |"
        lines += (
            [header + " Filled % |", "|---|---|---|---|---|"]
            if pct
            else [header, "|---|---|---|---|"]
        )
        for d in definitions:
            if d["table"] != t["table"] or not d["column"]:
                continue
            link = f"[{Path(d['rule']).stem}]({d['rule']})" if d["rule"] else ""
            filled = pct.get((d["table"], d["column"]), "absent")
            row = f"| `{d['column']}` | {d['type']} | {d['meaning']} | {link} |"
            lines.append(row + (f" {filled} |" if pct else ""))
            rows.append({**d, **({"filled_pct": filled} if pct else {})})
    out.mkdir(parents=True, exist_ok=True)
    (out / "data_dictionary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    write_csv(rows, out / "data_dictionary.csv")
    print(f"  {len(rows)} columns in {len(tables)} tables written to {out}")


def anchor(table):
    return table.replace(".", "").lower()  # GitHub heading anchor


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dbs", nargs="*", default=[], type=Path)
    parser.add_argument("--study", type=Path)
    parser.add_argument("--stats", action="store_true", help="add the filled %% of each column")
    parser.add_argument("--out", type=Path, default=ROOT / "dictionary")
    args = parser.parse_args()
    definitions = read_csv(DEFINITIONS)
    pct = {}
    if args.study:
        problems, pct = check(definitions, args.dbs, args.study, args.stats)
        if problems:
            print("Dictionary does not match the databases:\n  " + "\n  ".join(problems))
            sys.exit(1)
        print("  every column in the databases has a definition of the right type")
    publish(definitions, args.out, pct)


if __name__ == "__main__":
    main()
